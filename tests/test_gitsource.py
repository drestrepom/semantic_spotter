from conftest import git

from semantic_spotter import gitsource


async def test_reads_committed_content_not_worktree(make_repo):
    repo, sha = make_repo({"a.go": "package a\n// v1\n"})
    (repo / "a.go").write_text("package a\n// sucio\n")
    files = await gitsource.list_files(repo, sha)
    assert [f.path for f in files] == ["a.go"]
    blobs = await gitsource.read_blobs(repo, [f.oid for f in files])
    assert blobs[files[0].oid] == b"package a\n// v1\n"
    assert await gitsource.resolve_rev(repo, "HEAD") == sha


async def test_read_blobs_many(make_repo):
    repo, sha = make_repo({f"f{i}.go": f"package f\n// {i}\n" * (i + 1) for i in range(5)})
    files = await gitsource.list_files(repo, sha)
    blobs = await gitsource.read_blobs(repo, [f.oid for f in files])
    assert len(blobs) == 5
    assert blobs[next(f.oid for f in files if f.path == "f3.go")].count(b"\n") == 8


def test_is_candidate():
    assert gitsource.is_candidate("pkg/a.go", include_tests=False)
    assert not gitsource.is_candidate("pkg/a_test.go", include_tests=False)
    assert gitsource.is_candidate("pkg/a_test.go", include_tests=True)
    assert not gitsource.is_candidate("src/a.spec.ts", include_tests=False)
    assert not gitsource.is_candidate("src/a.test.tsx", include_tests=False)
    assert not gitsource.is_candidate("types/a.d.ts", include_tests=True)
    assert not gitsource.is_candidate("api/a.pb.go", include_tests=True)
    assert not gitsource.is_candidate("vendor/x/a.go", include_tests=True)
    assert not gitsource.is_candidate("web/node_modules/x/a.ts", include_tests=True)


def test_is_generated():
    assert gitsource.is_generated(b"// Code generated by protoc. DO NOT EDIT.\npackage a\n")
    assert not gitsource.is_generated(b"package a\n// Code generated by hand\n")


async def test_staged_tree_and_merge_base(make_repo):
    repo, base = make_repo({"a.go": "package a\n"})
    git(repo, "checkout", "-q", "-b", "feature")
    _, head = make_repo({"b.go": "package b\n"})
    assert await gitsource.merge_base(repo, base, head) == base
    assert await gitsource.tree_of(repo, head) == git(repo, "rev-parse", "HEAD^{tree}")

    (repo / "c.go").write_text("package c\n")
    (repo / "d.go").write_text("package d\n")  # sin stagear: no entra
    git(repo, "add", "c.go")
    staged = await gitsource.staged_tree(repo)
    assert [f.path for f in await gitsource.list_files(repo, staged)] == ["a.go", "b.go", "c.go"]
    assert await gitsource.read_file(repo, staged, "c.go") == b"package c\n"


async def test_history_attributes_merged_changes_to_branch_commits(make_repo):
    repo, root = make_repo({"a.go": "package a\n"})
    git(repo, "checkout", "-q", "-b", "side")
    _, side = make_repo({"b.go": "package b\n"})
    git(repo, "checkout", "-q", "-")
    (repo / "a.go").unlink()
    _, main = make_repo({"c.go": "package c\n"})
    git(repo, "merge", "-q", "--no-ff", "-m", "merge", "side")
    merge = git(repo, "rev-parse", "HEAD")

    commits = await gitsource.history(repo, "HEAD")
    assert [c.sha for c in commits][0] == root and commits[-1].sha == merge
    changed = {c.sha: [f.path for f in c.changed] for c in commits}
    assert changed[root] == ["a.go"]
    assert changed[side] == ["b.go"]
    assert changed[main] == ["c.go"]  # el borrado de a.go no cuenta
    # El merge contra su primer padre trae b.go, pero sus commits ya salieron antes.
    assert [c.sha for c in commits].index(side) < [c.sha for c in commits].index(merge)
    assert [c.sha for c in await gitsource.history(repo, "HEAD", since=main)] == [side, merge]
