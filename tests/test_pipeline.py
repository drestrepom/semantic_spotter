import asyncio

from conftest import count_extractions

from semantic_spotter import gitsource, pipeline
from semantic_spotter.pipeline import (
    EmbeddingPlan,
    ExtractOptions,
    RateLimiter,
    RateLimits,
    index_commit,
    index_history,
    plan_embeddings,
    run_embeddings,
)
from semantic_spotter.store import Store

GO_A = """package a

func Sum(xs []int) int {
	total := 0
	for _, x := range xs {
		total += x
	}
	return total
}
"""

GO_GEN = "// Code generated by x. DO NOT EDIT.\n" + GO_A


async def _scan(repo, sha, embedder, options=ExtractOptions()):
    store = await Store.open(repo, embedder.model, embedder.dim)
    snippets = await index_commit(store, repo, sha, options)
    plan = await plan_embeddings(store, repo, snippets, lambda: embedder)
    await run_embeddings(store, embedder, plan)
    return store, snippets


async def test_skips_generated_and_tests(make_repo, fake_embedder):
    repo, sha = make_repo({"a.go": GO_A, "gen.go": GO_GEN, "a_test.go": GO_A})
    _, snippets = await _scan(repo, sha, fake_embedder)
    assert {s.file_path for s in snippets} == {"a.go"}
    # Los tests se filtran al consultar, no al extraer: el mismo árbol los incluye.
    _, with_tests = await _scan(repo, sha, fake_embedder, ExtractOptions(include_tests=True))
    assert {s.file_path for s in with_tests} == {"a.go", "a_test.go"}


async def test_cache_avoids_reembedding(make_repo, fake_embedder, monkeypatch):
    repo, sha1 = make_repo({"a.go": GO_A})
    store, snippets = await _scan(repo, sha1, fake_embedder)
    assert len(fake_embedder.embedded) == len(snippets) > 0

    # Mismo commit: nada nuevo que embeber ni que extraer.
    extracted = count_extractions(monkeypatch)
    _, again = await _scan(repo, sha1, fake_embedder)
    assert again == snippets
    assert extracted == []
    assert len(fake_embedder.embedded) == len(snippets)

    # Nuevo commit: el archivo movido reutiliza su blob y sus embeddings; solo se
    # extrae y se paga lo nuevo.
    (repo / "a.go").rename(repo / "moved.go")
    repo, sha2 = make_repo({"b.go": GO_A.replace("Sum", "Total")})
    before = len(fake_embedder.embedded)
    _, snippets2 = await _scan(repo, sha2, fake_embedder)
    assert {s.file_path for s in snippets2} == {"moved.go", "b.go"}
    assert extracted == ["b.go"]
    new_texts = fake_embedder.embedded[before:]
    assert len(new_texts) == 1 and "Total" in new_texts[0]

    # El árbol del commit anterior sigue registrado con sus rutas.
    _, old = await _scan(repo, sha1, fake_embedder)
    assert {s.file_path for s in old} == {"a.go"}
    vectors = await store.load_vectors([s.content_hash for s in snippets2])
    assert vectors.shape == (len(snippets2), fake_embedder.dim)


async def test_db_does_not_store_text(make_repo, fake_embedder):
    repo, sha = make_repo({"a.go": GO_A})
    store, snippets = await _scan(repo, sha, fake_embedder)
    for name in (await store._db.list_tables()).tables:
        schema = await (await store._db.open_table(name)).schema()
        assert "text" not in schema.names, name
    # El texto embebido se recuperó del blob y coincide con lo que hashea el extractor.
    assert fake_embedder.embedded[0].startswith("func Sum(xs []int) int {")


async def test_new_extract_version_reextracts_without_reembedding(
    make_repo, fake_embedder, monkeypatch
):
    repo, sha = make_repo({"a.go": GO_A})
    _, snippets = await _scan(repo, sha, fake_embedder)
    embedded = len(fake_embedder.embedded)

    monkeypatch.setattr(pipeline, "EXTRACT_VERSION", pipeline.EXTRACT_VERSION + 1)
    extracted = count_extractions(monkeypatch)
    _, again = await _scan(repo, sha, fake_embedder)
    assert again == snippets
    assert extracted == ["a.go"]
    assert len(fake_embedder.embedded) == embedded


async def test_concurrency_is_bounded_by_semaphore(make_repo, fake_embedder):
    repo, _ = make_repo({"a.go": GO_A})
    store = await Store.open(repo, fake_embedder.model, fake_embedder.dim)
    n = 12
    # tpm=1 → batch_tokens=1 → un texto por lote, 12 lotes en paralelo.
    plan = EmbeddingPlan([f"h{i}" for i in range(n)], [f"t{i}" for i in range(n)], [1] * n)
    limits = RateLimits(tpm=1)
    limiter = RateLimiter(RateLimits())  # sin esperas reales
    await run_embeddings(store, fake_embedder, plan, limits=limits, concurrency=3, limiter=limiter)
    assert sorted(fake_embedder.embedded) == sorted(plan.texts)
    assert fake_embedder.max_in_flight == 3
    assert len(await store.missing_hashes(plan.hashes)) == 0


async def test_rate_limiter_spaces_requests():
    now = [0.0]
    sleeps = []

    async def sleep(s):
        sleeps.append(s)
        now[0] += s

    limiter = RateLimiter(RateLimits(rpm=3, tpm=12), sleep=sleep, clock=lambda: now[0])
    await limiter.acquire(12)
    await limiter.acquire(6)
    await limiter.acquire(6)
    # Tras 12 tokens: max(60/3, 60*12/12) = 60s; tras 6: max(20, 30) = 30s.
    assert sleeps == [60.0, 30.0]
    assert RateLimits(tpm=10_000).batch_tokens == 10_000


async def test_index_history_records_first_sighting(make_repo, fake_embedder):
    repo, first = make_repo({"a.go": GO_A})
    _, second = make_repo({"b.go": GO_A, "a.go": GO_A + "\n// cola\n"})
    _, third = make_repo({"a.go": GO_A.replace("Sum", "Total")})
    store = await Store.open(repo, fake_embedder.model, fake_embedder.dim)
    options = ExtractOptions()

    stats = await index_history(store, repo, "HEAD", None, options)
    assert (stats.commits, stats.walked) == (3, 3)
    snippets = await index_commit(store, repo, third, options)
    seen = await store.first_seen(snippets, options.key)
    by_file = {
        s.file_path: seen[(s.file_path, s.content_hash)].commit_sha
        for s in snippets
        if s.unit == "function"
    }
    # La copia en b.go aparece en el segundo commit; la función de a.go se renombró en el tercero.
    assert by_file == {"b.go": second, "a.go": third}
    seen_old = await store.first_seen(await index_commit(store, repo, first, options), options.key)
    assert {x.commit_sha for x in seen_old.values()} == {first}

    # Una segunda corrida no vuelve a recorrer nada.
    again = await index_history(store, repo, "HEAD", None, options)
    assert again.walked == 0 and again.sightings == 0


async def test_concurrent_index_history_writes_sightings_once(
    make_repo, fake_embedder, monkeypatch
):
    repo, _ = make_repo({"a.go": GO_A})
    make_repo({"b.go": GO_A.replace("Sum", "Total")})
    # Las dos corridas leen qué falta antes de que cualquiera escriba.
    barrier = asyncio.Barrier(2)
    read_blobs = gitsource.read_blobs

    async def read_after_both(*args):
        await barrier.wait()
        return await read_blobs(*args)

    monkeypatch.setattr(gitsource, "read_blobs", read_after_both)
    stores = [await Store.open(repo, fake_embedder.model, fake_embedder.dim) for _ in range(2)]
    stats = await asyncio.gather(
        *(index_history(s, repo, "HEAD", None, ExtractOptions()) for s in stores)
    )
    # La que tomó el lock segunda encuentra todo escrito: no agrega nada.
    assert sorted(s.sightings for s in stats)[0] == 0
    assert sorted(s.sightings for s in stats)[1] > 0
